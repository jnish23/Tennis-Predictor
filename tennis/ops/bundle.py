"""Pack and unpack the two bundles the cloud setup moves around.

* **state**  -- what the daily job needs to rebuild everything: the raw source
  CSVs (the cache is the working copy, not the website), the per-tournament and
  dated ongoing archives, the current odds workbooks, the odds rows that cannot
  be regenerated (the CBO Challenger prices), and the trained models and
  reports. A fresh runner restores this, then reloads the database from it.
* **serve**  -- what the dashboard needs and nothing else: a slim SQLite file
  holding only the tables the pages read, the serving artifacts, and the cached
  draw sheets. About 6.1 of the laptop database's 6.5 GB is `odds_quotes`, a
  research table the dashboard must never touch, so the slim file is built by
  copying the serving tables into a freshly created schema rather than by
  deleting from the big one.

Archives are tar streams compressed with zstd, and nothing is extracted in
place: `fetch_serve` stages the new files and swaps them in one rename at a
time, so a dashboard reading mid-update sees the old copy or the new one.
"""
from __future__ import annotations

import contextlib
import fcntl
import json
import logging
import os
import shutil
import sqlite3
import tarfile
import tempfile
import threading
import time
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import zstandard

from tennis.config import ARTIFACTS, DATA, DB_PATH
from tennis.db.schema import init_db

log = logging.getLogger(__name__)

# Tables the dashboard (and the Predictor behind it) read. `odds_quotes`,
# `te_matches`, `te_scrape_log`, `features`, `backtest`, `draws`, `sim_results`
# and `predictions` are research or scratch tables: the slim file carries them
# empty (the schema is created whole) so a stray query returns no rows rather
# than failing. `odds` is in that group on purpose: the dashboard only ever
# counted it (25 MB for a status-page number), so its two counts travel in
# serve_meta.json instead -- see `odds_summary`.
SERVE_TABLES = (
    "matches", "players", "tournaments", "rankings", "elo_state",
    "odds_snapshots", "pipeline_state", "tourney_xref", "feed_player_xref",
    "player_alias",
)
SERVE_ARTIFACTS = (
    "models_pooled.pkl", "feature_state_atp.pkl", "feature_state_wta.pkl",
    "backtest_pooled.parquet", "backtest_report_atp.json",
    "backtest_report_wta.json", "last_daily_run.json",
)
# Reports are carried in state because their `market_lines` block comes from
# the research table the cloud does not have; see evaluate.full_report.
STATE_ARTIFACTS = (
    "models_pooled.pkl", "backtest_pooled.parquet",
    "backtest_report_atp.json", "backtest_report_wta.json",
)
RAW_STATE_DIRS = ("tennismylife", "tennismylife_ongoing", "tennismylife_dated",
                  "tennisdata")
# Books whose rows are not regenerated by the pipeline (CBO is a scrape of a
# site with no archive). Everything else in `odds` is rebuilt every run.
PERSISTED_ODDS_BOOKS = ("CBO",)

SNAPSHOTS_FILE = "odds_snapshots.parquet"
ODDS_EXTRA_FILE = "odds_extra.parquet"
SERVE_META = "serve_meta.json"
DRAW_MAX_AGE_DAYS = 14


# --------------------------------------------------------------------------
# archives
# --------------------------------------------------------------------------
@contextlib.contextmanager
def _tar_writer(path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp{os.getpid()}")
    with open(tmp, "wb") as fh:
        cctx = zstandard.ZstdCompressor(level=10, threads=-1)
        with cctx.stream_writer(fh, closefd=False) as zw:
            with tarfile.open(fileobj=zw, mode="w|") as tar:
                yield tar
    os.replace(tmp, path)


def _add(tar: tarfile.TarFile, src: Path, arcname: str) -> int:
    if not src.exists():
        return 0
    if src.is_dir():
        n = 0
        for p in sorted(src.rglob("*")):
            if p.is_file() and not p.name.startswith("."):
                tar.add(p, arcname=f"{arcname}/{p.relative_to(src).as_posix()}")
                n += 1
        return n
    tar.add(src, arcname=arcname)
    return 1


def _extract(archive: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    with open(archive, "rb") as fh:
        with zstandard.ZstdDecompressor().stream_reader(fh) as zr:
            with tarfile.open(fileobj=zr, mode="r|") as tar:
                tar.extractall(dest, filter="data")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# --------------------------------------------------------------------------
# odds tables that live outside the database between runs
# --------------------------------------------------------------------------
def export_snapshots(con: sqlite3.Connection, path: Path) -> int:
    df = pd.read_sql("SELECT * FROM odds_snapshots", con)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp{os.getpid()}")
    df.to_parquet(tmp, index=False)
    os.replace(tmp, path)
    return len(df)


def import_snapshots(con: sqlite3.Connection, path: Path) -> int:
    """Merge a snapshots parquet into the table. Idempotent on the primary key."""
    if not path.exists():
        return 0
    df = pd.read_parquet(path)
    if df.empty:
        return 0
    cols = [c for c in df.columns
            if c in {r[1] for r in con.execute("PRAGMA table_info(odds_snapshots)")}]
    data = df[cols].astype(object).where(df[cols].notna(), None)
    con.executemany(
        f"INSERT OR IGNORE INTO odds_snapshots({','.join(cols)}) "
        f"VALUES({','.join('?' * len(cols))})",
        data.itertuples(index=False, name=None))
    con.commit()
    return len(df)


def export_odds_extra(con: sqlite3.Connection, path: Path) -> int:
    q = ",".join("?" * len(PERSISTED_ODDS_BOOKS))
    df = pd.read_sql(f"SELECT * FROM odds WHERE book IN ({q})", con,
                     params=PERSISTED_ODDS_BOOKS)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(path, index=False)
    return len(df)


def import_odds_extra(con: sqlite3.Connection, path: Path) -> int:
    if not path.exists():
        return 0
    df = pd.read_parquet(path)
    con.executemany(
        "INSERT OR REPLACE INTO odds(match_id, book, win_price, lose_price) VALUES(?,?,?,?)",
        df[["match_id", "book", "win_price", "lose_price"]].itertuples(index=False, name=None))
    con.commit()
    return len(df)


# --------------------------------------------------------------------------
# state bundle
# --------------------------------------------------------------------------
def pack_state(out: Path, *, db_path: Path = DB_PATH, data: Path = DATA,
               artifacts: Path = ARTIFACTS) -> dict:
    """Everything a fresh runner needs to rebuild the site, except the
    snapshots (those have their own, more frequently updated asset)."""
    out = Path(out)
    counts: dict[str, int] = {}
    with tempfile.TemporaryDirectory() as td:
        extra = Path(td) / ODDS_EXTRA_FILE
        if Path(db_path).exists():
            con = sqlite3.connect(str(db_path))
            try:
                counts["odds_extra"] = export_odds_extra(con, extra)
            finally:
                con.close()
        with _tar_writer(out) as tar:
            for d in RAW_STATE_DIRS:
                counts[d] = _add(tar, data / "raw" / d, f"data/raw/{d}")
            counts["odds_extra_file"] = _add(tar, extra, f"data/{ODDS_EXTRA_FILE}")
            for f in STATE_ARTIFACTS:
                counts[f] = _add(tar, artifacts / f, f"artifacts/{f}")
    counts["bytes"] = out.stat().st_size
    return counts


def unpack_state(archive: Path, *, data: Path = DATA, artifacts: Path = ARTIFACTS) -> None:
    with tempfile.TemporaryDirectory(dir=str(data.parent)) as td:
        stage = Path(td)
        _extract(Path(archive), stage)
        for src_root, dst_root in ((stage / "data", data), (stage / "artifacts", artifacts)):
            if not src_root.exists():
                continue
            for p in src_root.rglob("*"):
                if p.is_file():
                    dst = dst_root / p.relative_to(src_root)
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    os.replace(p, dst)


# --------------------------------------------------------------------------
# serve bundle
# --------------------------------------------------------------------------
def build_slim_db(src: Path, dest: Path) -> dict[str, int]:
    """Copy the serving tables into a freshly created schema, then VACUUM.

    Creating the schema whole and copying selected tables in keeps primary keys
    and indexes exactly as `schema.py` defines them, which deleting from a
    6.5 GB file would not shrink without a VACUUM of the whole thing.
    """
    if dest.exists():
        dest.unlink()
    con = init_db(dest)
    counts: dict[str, int] = {}
    try:
        con.commit()
        con.execute("PRAGMA journal_mode=DELETE")
        # The copy order is arbitrary and the source already satisfied the keys.
        con.execute("PRAGMA foreign_keys=OFF")
        con.execute("ATTACH DATABASE ? AS s", (str(src),))
        have = {r[0] for r in con.execute("SELECT name FROM s.sqlite_master WHERE type='table'")}
        for t in SERVE_TABLES:
            if t not in have:
                counts[t] = 0
                continue
            mine = [r[1] for r in con.execute(f"PRAGMA main.table_info({t})")]
            theirs = {r[1] for r in con.execute(f"PRAGMA s.table_info({t})")}
            cols = ",".join(c for c in mine if c in theirs)
            con.execute(f"INSERT INTO main.{t}({cols}) SELECT {cols} FROM s.{t}")
            counts[t] = con.execute(f"SELECT COUNT(*) FROM main.{t}").fetchone()[0]
        con.commit()
        con.execute("DETACH DATABASE s")
        con.execute("VACUUM")
    finally:
        con.close()
    return counts


def odds_summary(con: sqlite3.Connection) -> dict:
    """Price rows, and distinct priced matches, for the status page.

    `odds` holds one row per (match, bookmaker), so the two differ.
    """
    try:
        rows, matches = con.execute(
            "SELECT COUNT(*), COUNT(DISTINCT match_id) FROM odds").fetchone()
    except sqlite3.Error:
        rows = matches = 0
    return {"rows": rows, "matches": matches}


def pack_serve(out: Path, *, db_path: Path = DB_PATH, data: Path = DATA,
               artifacts: Path = ARTIFACTS) -> dict:
    out = Path(out)
    with tempfile.TemporaryDirectory() as td:
        slim = Path(td) / "tennis.db"
        counts = build_slim_db(Path(db_path), slim)
        con = sqlite3.connect(str(slim))
        try:
            max_date = con.execute("SELECT MAX(tourney_date) FROM matches").fetchone()[0]
        finally:
            con.close()
        src = sqlite3.connect(str(db_path))
        try:
            odds = odds_summary(src)
        finally:
            src.close()
        meta = {"built_at": _now(), "max_tourney_date": max_date, "rows": counts,
                "odds": odds}
        meta_path = Path(td) / SERVE_META
        meta_path.write_text(json.dumps(meta, indent=2))
        with _tar_writer(out) as tar:
            _add(tar, slim, "data/tennis.db")
            _add(tar, meta_path, f"data/{SERVE_META}")
            for f in SERVE_ARTIFACTS:
                _add(tar, artifacts / f, f"artifacts/{f}")
            draws = data / "raw" / "draws"
            if draws.exists():
                # Only what the live pages request; the directory also holds
                # exploration dumps that nothing reads.
                for pat in ("draws_*.json", "fixtures_*.json", "range_*.json",
                            "calendar_*.json"):
                    for p in sorted(draws.glob(pat)):
                        # Weeks-old sheets would show finished events as live.
                        if time.time() - p.stat().st_mtime <= DRAW_MAX_AGE_DAYS * 86400:
                            _add(tar, p, f"data/raw/draws/{p.name}")
    meta["bytes"] = out.stat().st_size
    return meta


def local_meta(data: Path = DATA) -> dict | None:
    try:
        return json.loads((data / SERVE_META).read_text())
    except (FileNotFoundError, ValueError):
        return None


def is_stale(max_age_hours: float = 6.0, *, data: Path = DATA,
             db_path: Path | None = None) -> bool:
    """True when there is no local copy, or it was built more than N hours ago."""
    db_path = db_path or (data / "tennis.db")
    meta = local_meta(data)
    if meta is None or not db_path.exists():
        return True
    try:
        built = datetime.fromisoformat(meta["built_at"])
    except (KeyError, ValueError):
        return True
    return (datetime.now(timezone.utc) - built).total_seconds() > max_age_hours * 3600


def fetch_serve(url: str, *, data: Path = DATA, artifacts: Path = ARTIFACTS) -> dict:
    """Download the serve bundle and swap it in.

    Staged beside the destination (same filesystem, so `os.replace` is atomic)
    and guarded by a file lock, so two sessions starting together do not both
    download 250 MB. The database goes last: its metadata file is what
    `is_stale` reads, so a half-finished swap reads as stale and retries.
    """
    import requests

    data.mkdir(parents=True, exist_ok=True)
    lock = data / ".fetch.lock"
    with open(lock, "w") as lf:
        fcntl.flock(lf, fcntl.LOCK_EX)
        # Another session may have finished while we waited.
        if not is_stale(data=data):
            return local_meta(data) or {}
        with tempfile.TemporaryDirectory(dir=str(data)) as td:
            td = Path(td)
            archive = td / "serve.tar.zst"
            t0 = time.time()
            with requests.get(url, stream=True, timeout=120) as r:
                r.raise_for_status()
                with open(archive, "wb") as fh:
                    for chunk in r.iter_content(1 << 20):
                        fh.write(chunk)
            stage = td / "stage"
            _extract(archive, stage)
            if not (stage / "data" / "tennis.db").exists():
                raise RuntimeError("serve bundle has no tennis.db; refusing to swap")
            for p in sorted((stage / "artifacts").glob("*")):
                artifacts.mkdir(parents=True, exist_ok=True)
                os.replace(p, artifacts / p.name)
            draws = stage / "data" / "raw" / "draws"
            if draws.exists():
                (data / "raw" / "draws").mkdir(parents=True, exist_ok=True)
                for p in draws.glob("*.json"):
                    os.replace(p, data / "raw" / "draws" / p.name)
            for sfx in ("-wal", "-shm"):
                (data / f"tennis.db{sfx}").unlink(missing_ok=True)
            os.replace(stage / "data" / "tennis.db", data / "tennis.db")
            os.replace(stage / "data" / SERVE_META, data / SERVE_META)
            log.info("fetched serve bundle in %.0fs", time.time() - t0)
    return local_meta(data) or {}


# --------------------------------------------------------------------------
# background refresh
# --------------------------------------------------------------------------
BG_RETRY_S = 600.0
_bg_lock = threading.Lock()
_bg: dict = {"thread": None, "error": None, "failed_at": 0.0, "seen": None}


def start_background_fetch(url: str, *, data: Path = DATA,
                           artifacts: Path = ARTIFACTS) -> str:
    """Refresh the serve bundle on a daemon thread; never blocks the caller.

    Returns 'running' (one is already in flight), 'started', or 'backoff' (the
    last attempt failed less than BG_RETRY_S ago, so a flapping download is not
    retried on every page rerun). The thread only moves files; it does not
    touch any Streamlit cache -- the caller drops those on a later rerun, once
    `bundle_changed` says the new copy is in place.
    """
    with _bg_lock:
        t = _bg["thread"]
        if t is not None and t.is_alive():
            return "running"
        if _bg["error"] and time.time() - _bg["failed_at"] < BG_RETRY_S:
            return "backoff"

        def work():
            try:
                fetch_serve(url, data=data, artifacts=artifacts)
                _bg["error"] = None
            except Exception as exc:  # noqa: BLE001 - surfaced via background_error
                log.warning("background refresh failed: %s", exc)
                _bg["error"] = str(exc)
                _bg["failed_at"] = time.time()

        _bg["thread"] = threading.Thread(target=work, name="serve-refresh", daemon=True)
        _bg["thread"].start()
        return "started"


def background_error() -> str | None:
    return _bg["error"]


def bundle_changed(data: Path = DATA) -> bool:
    """True once, the first time a different `built_at` is seen than last call.

    The first call only records a baseline. Process-wide on purpose: Streamlit's
    caches are shared by every session in the process, so one clear is enough.
    """
    built = (local_meta(data) or {}).get("built_at")
    with _bg_lock:
        prev, _bg["seen"] = _bg["seen"], built
    return prev is not None and built is not None and built != prev


def main() -> None:
    """Small CLI so workflows and the laptop use the same code.

        python -m tennis.ops.bundle unpack-state state.tar.zst
        python -m tennis.ops.bundle pack-state OUT.tar.zst      # seed from a laptop
        python -m tennis.ops.bundle export-snapshots OUT.parquet
    """
    import argparse
    ap = argparse.ArgumentParser(description=main.__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["unpack-state", "pack-state", "export-snapshots"])
    ap.add_argument("path", type=Path)
    a = ap.parse_args()
    logging.basicConfig(level=logging.INFO)
    if a.cmd == "unpack-state":
        unpack_state(a.path)
    elif a.cmd == "pack-state":
        print(json.dumps(pack_state(a.path), indent=2))
    else:
        con = sqlite3.connect(str(DB_PATH))
        try:
            print(export_snapshots(con, a.path), "snapshots")
        finally:
            con.close()


if __name__ == "__main__":
    main()
